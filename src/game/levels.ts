// Helper to look up a level by ID or index
export function getLevelById(levelId: string): LevelData | undefined {
  return HANDCRAFTED_LEVELS.find(lvl => lvl.id === levelId);
}

export function getLevelByIndex(index: number): LevelData | undefined {
  if (index >= 0 && index < HANDCRAFTED_LEVELS.length) {
    return HANDCRAFTED_LEVELS[index];
  }
  return undefined;
}

export function getLevelsByDifficulty(difficulty: LevelData['difficulty']): LevelData[] {
  return HANDCRAFTED_LEVELS.filter(lvl => lvl.difficulty === difficulty);
}
